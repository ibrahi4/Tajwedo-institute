export function getNoorAlBayanLessonBySlug(slug: string): CurriculumLesson | undefined {
  const normalized = decodeURIComponent(slug).toLowerCase().trim();
  return NOOR_AL_BAYAN_LESSONS.find(
    (l) =>
      l.slug.toLowerCase() === normalized ||
      l.id.toLowerCase() === normalized ||
      (l.aliases && l.aliases.some((a) => a.toLowerCase() === normalized))
  );
}

export function getAdjacentNoorLessons(slug: string): {
  prev: CurriculumLesson | null;
  next: CurriculumLesson | null;
} {
  const current = getNoorAlBayanLessonBySlug(slug);
  if (!current) return { prev: null, next: null };
  const idx = NOOR_AL_BAYAN_LESSONS.findIndex((l) => l.id === current.id);
  return {
    prev: idx > 0 ? NOOR_AL_BAYAN_LESSONS[idx - 1] : null,
    next: idx >= 0 && idx + 1 < NOOR_AL_BAYAN_LESSONS.length ? NOOR_AL_BAYAN_LESSONS[idx + 1] : null,
  };
}

